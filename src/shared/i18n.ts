export function resolveLocale(setting: 'system' | 'en' | 'zh-CN', systemLocale: string): Locale {
  if (setting === 'en' || setting === 'zh-CN') return setting
  return systemLocale.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en'
}

export function translate(locale: Locale, key: Key, params?: Record<string, string | number>): string {
  let text = dicts[locale][key] ?? dicts.en[key]
  if (params) for (const [k, v] of Object.entries(params)) text = text.split(`{${k}}`).join(String(v))
  return text
}

export type T = (key: Key, params?: Record<string, string | number>) => string

export function translator(locale: Locale): T {
  return (key, params) => translate(locale, key, params)
}
